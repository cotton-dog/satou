    /* =========================
       更新时间
    ========================= */

    function updateTime(){

        if(!timeElement) return;

        const now = new Date();

        const hh =
            String(
                now.getHours()
            ).padStart(2,"0");

        const mm =
            String(
                now.getMinutes()
            ).padStart(2,"0");


        timeElement.textContent =
            `${hh}:${mm}`;
    }


    /* =========================
       浅色 / 深色
    ========================= */

    function setLightMode(isLight){

        if(!statusBar) return;

        statusBar.classList.toggle(
            "on-light",
            isLight
        );
    }


    return{

        create,

        updateTime,

        setLightMode

    };

